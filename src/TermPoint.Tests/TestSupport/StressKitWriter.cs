using System.Text;
using TermPoint.Services.SectionImport;

namespace TermPoint.Tests.TestSupport;

/// <summary>One file of the hand-test kit as written: its scenario, what Check should show, and where it went.</summary>
/// <param name="Scenario">The scenario.</param>
/// <param name="Built">The file's content and expected outcome.</param>
/// <param name="FileName">The file name in the kit folder (number, name and extension).</param>
internal sealed record KitFile(StressScenario Scenario, StressBuilt Built, string FileName);

/// <summary>
/// Writes the hand-test kit for the Import Sections flyout into a folder: a copy of the real-data database to
/// open in TermPoint, one numbered file for every scenario in <see cref="StressScenarios"/>, and a
/// <c>CHECKLIST.md</c> that says for each file which semester to select, what to press and what should happen,
/// plus the steps that need Excel or the running app. Everything is built from the same generators the
/// automated stress tests use. The folder holds private data (the database copy and files made from it): the
/// caller chooses where it goes and nothing here writes anywhere else.
/// </summary>
internal static class StressKitWriter
{
    /// <summary>The environment variable that names the folder the kit is written to (the writer test is skipped without it).</summary>
    public const string EnvironmentVariable = "TERMPOINT_IMPORT_STRESS_KIT";

    /// <summary>The name of the database copy in the kit.</summary>
    public const string DatabaseFileName = "BIOL-stress.db";

    /// <summary>The name of the checklist in the kit.</summary>
    public const string ChecklistFileName = "CHECKLIST.md";

    /// <summary>
    /// Writes the kit: the database copy, every scenario file and the checklist.
    /// </summary>
    /// <param name="folder">Where to write (created if it does not exist; existing files with the same names are replaced, nothing else is touched).</param>
    /// <returns>Every scenario file written.</returns>
    /// <exception cref="InvalidOperationException">The folder is inside the real database's own folder, which the kit must never write to.</exception>
    public static IReadOnlyList<KitFile> Write(string folder)
    {
        var target = Path.GetFullPath(folder);
        var sourceFolder = Path.GetFullPath(Path.GetDirectoryName(RealImportDb.SourcePath)!);
        var programData = Path.GetFullPath(Path.Combine(sourceFolder, ".."));
        if (target.StartsWith(programData, StringComparison.OrdinalIgnoreCase))
            throw new InvalidOperationException("The kit must not be written inside TermPoint's own data folder.");

        Directory.CreateDirectory(target);

        // A plain file copy: the original is never opened.
        File.Copy(RealImportDb.SourcePath, Path.Combine(target, DatabaseFileName), overwrite: true);

        var written = new List<KitFile>();
        using (var ctx = StressContext.Open())
        {
            foreach (var scenario in StressScenarios.All)
            {
                var built = scenario.Build(ctx);
                var fileName = scenario.FileBaseName + built.Extension;
                File.WriteAllBytes(Path.Combine(target, fileName), built.Bytes);
                written.Add(new KitFile(scenario, built, fileName));
            }
        }

        File.WriteAllText(Path.Combine(target, ChecklistFileName), BuildChecklist(written), new UTF8Encoding(false));
        return written;
    }

    /// <summary>
    /// Writes the checklist in plain words: set-up, one block per file, the steps that need Excel, the
    /// stress steps and the flows, each step with a blank line to write the result on.
    /// </summary>
    /// <param name="files">Every scenario file of the kit.</param>
    /// <returns>The Markdown text.</returns>
    public static string BuildChecklist(IReadOnlyList<KitFile> files)
    {
        var text = new StringBuilder();
        void Line(string line = "") => text.Append(line).Append("\r\n");
        const string ResultLine = "- **Result:** ______________________________________________";

        Line("# Import Sections: hand-test checklist");
        Line();
        Line("These files and the database copy were generated by `WriteImportStressKit` from a copy of `BIOL-TT.db`. " +
             "Each numbered file has a block below that says which semester to select, what to press and what you should see. " +
             "Write what actually happened on the **Result** line, and note anything that reads wrongly, even if it matches.");
        Line();
        Line("## 0. Before you start");
        Line();
        Line($"1. Copy `{StressKitWriter.DatabaseFileName}` to a new folder (for example `stress-run-1`) and open **that copy** in TermPoint. " +
             "Keep this folder's copy untouched, so you can start again by copying it afresh. Never use the real `BIOL-TT.db` for this.");
        Line("2. In the section list, choose **exactly one** semester before each step: the one named in the step. " +
             "The first line of the Import Sections flyout (Files, then Import Sections…) says \"The current semester is …\": check it names the right one.");
        Line("3. The semesters of 2026-2027 called Winter, Early Summer, Summer and Late Summer are empty in this database; Fall 2026-2027 already has sections.");
        Line("4. Words used: **Choose file** is the flyout's button (it checks the file as soon as you pick it); **Import**, **Cancel**, **Copy list** and **Check again** are the flyout's other buttons. " +
             "Unless a step says **Import**, finish with **Cancel** (or just Choose the next file): nothing is changed until you press Import.");
        Line("5. Do the steps in order where a step says \"after file NN\"; otherwise any order works. If something goes wrong badly, copy the database afresh and carry on.");
        Line();

        Line("## 1. The files");
        Line();
        foreach (var file in files)
        {
            var s = file.Scenario;
            Line($"### {file.FileName}");
            Line();
            Line($"- **Select first:** {s.Semester}");
            if (s.ImportFirst is int first)
                Line($"- **Before this:** do it after you have imported file {first:00} into {s.Semester}.");
            Line($"- **What it tests:** {s.Purpose}");
            Line($"- **What to do:** {s.Do}");
            Line($"- **You should see:** {file.Built.Expect}");
            if (file.Built.Hint is not null)
                Line($"- **Note:** {file.Built.Hint}");
            Line(ResultLine);
            Line();
        }

        Line("## 2. Copy list into Excel (files 07, 31 and 43)");
        Line();
        Line("After the problems list appears, press **Copy list**, open a new Excel sheet and paste into cell A1.");
        Line();
        Line("- You should get three columns headed Row, Column and Problem, one problem per line, with the row numbers in the first column.");
        Line("- The Row column should sort as numbers. A problem about the whole file has an empty Row.");
        Line("- File 31 has four Problem cells whose text starts with `=`, `+`, `-` or `@`. Excel would run such a cell as a formula, so TermPoint puts an apostrophe in front of each one when it copies. " +
             "Each should paste as the plain text shown in the flyout (Excel hides the apostrophe; the formula bar may show it), with no `#NAME?`, no number and no warning. Write down what you see.");
        Line("- Also try pasting into Notepad and into an email: each problem should be one readable line.");
        Line(ResultLine);
        Line();

        Line("## 3. Excel round trips from file 00");
        Line();
        Line($"Aim at **Early Summer ({StressContext.TargetYear})**. File `{files.First(f => f.Scenario.Number == 0).FileName}` should show the Ready screen as listed in its block above before you start. " +
             "Each step below re-saves it from Excel under a new name (in your own folder, not the kit's) and chooses the new file.");
        Line();
        var roundTrips = new (string Id, string Do, string Expect)[]
        {
            ("E1", "Open file 00 in Excel and **leave it open**. In the flyout, press Choose file and pick that same file.",
                "The same Ready screen as before. TermPoint reads a workbook that is open in Excel; there should be no message that it can't open the file."),
            ("E2", "With file 00 still open in Excel, press Cancel and Choose file again; then make a change in Excel (for example correct a typo, **save** it, keep Excel open) and press Choose file again.",
                "The result follows the saved change, with no \"couldn't open\" message. (If the file is on a network drive, also try that.)"),
            ("E3", "Excel: File, Save As, type **CSV (Comma delimited) (*.csv)** (the Windows default, which is ANSI). Choose that file.",
                "Ready. Look at the new instructors list: Gagné, Müller and O’Brien should read exactly as in file 00, with the curly apostrophe in O’Brien and no stray characters (Excel wrote the file in the Windows ANSI code page, which TermPoint reads as Windows-1252). Write down exactly what you see."),
            ("E4", "Excel: Save As, type **CSV UTF-8 (Comma delimited) (*.csv)**. Choose that file.",
                "Ready, with every name exactly as in file 00 (accents and the apostrophe)."),
            ("E5", "Excel: Save As, type **Strict Open XML Spreadsheet (*.xlsx)**. Choose that file.",
                "Not specified: either the same Ready screen, or a plain message that TermPoint couldn't read it as an Excel workbook. Write down which. Either is acceptable if nothing breaks and the message is plain."),
            ("E6", "Excel: Save As, type **Excel 97-2003 Workbook (*.xls)**. Choose that file.",
                "\"TermPoint can import Excel workbooks (.xlsx) and CSV files (.csv).\""),
            ("E7", "In Explorer, rename that `.xls` file so it ends in `.xlsx` (accept the warning). Choose it.",
                "\"TermPoint couldn't read this file as an Excel workbook (.xlsx). Check that it opens in Excel, then save it again as .xlsx.\""),
            ("E8", "Excel: File, Info, Protect Workbook, Encrypt with Password; save as a new `.xlsx` with a password you remember. Choose it.",
                "The same \"couldn't read this file as an Excel workbook\" message (an encrypted workbook can't be read)."),
            ("E9", "Excel: open file 00, delete every row below the header row, and save as a new `.xlsx`. Choose it.",
                "\"This file has no sections to add.\" (the first screen after the check), and nothing changes."),
            ("E10", "Excel: Save As, type **Unicode Text (*.txt)**, then rename the file to end in `.csv`. Choose it.",
                "Not specified: it is UTF-16 with tabs between the columns. TermPoint now reads UTF-16 but not tab-separated files (a later item), so expect the \"first row doesn't have the column names\" refusal. Write down what you see."),
        };
        foreach (var (id, todo, expect) in roundTrips)
        {
            Line($"**{id}.** {todo}");
            Line();
            Line($"- **You should see:** {expect}");
            Line(ResultLine);
            Line();
        }

        Line("## 4. The flyout under stress");
        Line();
        var big = files.First(f => f.Scenario.Number == 40);
        var broken = files.First(f => f.Scenario.Number == 43);
        var tooBig = files.First(f => f.Scenario.Number == 42);
        var stress = new (string Id, string Do, string Expect)[]
        {
            ("S1", $"Select Late Summer ({StressContext.TargetYear}). Choose `{big.FileName}` and time how long until the Ready screen appears. Try to scroll the flyout and move the window while it works.",
                "The Ready screen appears within a few seconds and the window stays responsive. Write down how long it took and whether the window froze at all."),
            ("S2", "Press **Import** on that Ready screen and time it. Watch whether the window stays responsive.",
                "The Done message appears (it says how many sections, courses and instructors were added, and a second line about the new setup values and rooms). Write down the time and any freeze."),
            ("S3", "Look at the Sections list for Late Summer: scroll it, change the sort, open a section, switch to another semester and back.",
                "The list and the grid show the new sections without a long pause. Write down anything slow."),
            ("S4", "File, Save. Time it, then close TermPoint, open the same copy again and select Late Summer.",
                "The imported sections are all there after the reopen."),
            ("S5", $"Select Early Summer ({StressContext.TargetYear}). Choose `{broken.FileName}` and time it.",
                "The problems list (13,000 lines or so) appears. Write down how long it took, whether the window froze, whether the list scrolls smoothly, and whether the window can still be moved and closed."),
            ("S6", "Press **Copy list** on that list and paste into a new Excel sheet.",
                "Three columns, about 13,000 rows, no freeze. Write down how long the copy and the paste took."),
            ("S7", $"Choose `{tooBig.FileName}` (about 12 MB) and time how long the message takes to appear.",
                "The \"larger than TermPoint can import at once\" message appears at once (under a second). The window does not freeze."),
        };
        foreach (var (id, todo, expect) in stress)
        {
            Line($"**{id}.** {todo}");
            Line();
            Line($"- **You should see:** {expect}");
            Line(ResultLine);
            Line();
        }

        Line("## 5. Flows");
        Line();
        var corrected = files.First(f => f.Scenario.Number == 4);
        var flows = new (string Id, string Do, string Expect)[]
        {
            ("F1", "Choose file 01 (Winter) so the Ready screen shows, then press **Cancel**.",
                "The flyout goes back to its first screen. Nothing was added: Winter is still empty."),
            ("F2", $"Change something between Check and Import. Select Winter, import file 01 first if you have not, then Choose `{corrected.FileName}` so its Ready screen shows. " +
                   $"Now detach the Sections panel into its own window (or use a second window) and add a section to Winter by hand with the course and code named in file 04's note ({corrected.Built.Hint}). " +
                   "Go back to the flyout and press Import.",
                $"Nothing is imported. The flyout shows the up-to-date result with the notice \"{ImportMessages.ChangedNotice}\" and the section you added now counted as already there."),
            ("F3", "With a Ready screen showing for Winter (choose file 01 on a fresh copy of the database, or file 04), change the selected semester to Summer.",
                $"The result is dropped: \"{ImportMessages.SemesterChangedNotice}\""),
            ("F4", "Open a section's editor in a detached Sections panel (leave it open), then look at Files, Import Sections… and, if a Ready screen is showing, at its Import button.",
                $"The menu item is greyed out, and its tooltip (and the Import button's) says \"{ImportAvailability.EditingReason}\" Close the editor and it comes back."),
            ("F5", "Select two semesters at once and look at Files, Import Sections….",
                $"Greyed out with the tooltip \"{ImportAvailability.SeveralSemestersReason}\""),
            ("F6", "Read-only session: open the same database in a second TermPoint (or turn on reading mode in the settings) so that this one cannot write, then look at Files, Import Sections….",
                $"Greyed out with the tooltip \"{ImportAvailability.ReadOnlyReason}\""),
            ("F7", "After an import (file 01 into Winter): File, Save. Close TermPoint. Open the copy again and select Winter.",
                "All the imported sections are there."),
            ("F8", "After an import (any file), do **not** save: close TermPoint straight away.",
                "TermPoint saves on exit without asking (the import is an ordinary edit, saved like any other). Reopen the copy and check the imported sections are there: nothing was lost."),
            ("F9", "Import file 01 into Winter, then switch to Summer and use Academic Years, Empty semester on Winter.",
                "The semester empties (the undo hint after the import said to switch to another semester first). The courses, instructors and setup values the import created stay."),
        };
        foreach (var (id, todo, expect) in flows)
        {
            Line($"**{id}.** {todo}");
            Line();
            Line($"- **You should see:** {expect}");
            Line(ResultLine);
            Line();
        }

        Line("## 6. Anything else you noticed");
        Line();
        Line("Wording that was confusing, buttons that did nothing, pauses, odd layout:");
        Line();
        Line("________________________________________________________________________________");
        Line();
        return text.ToString();
    }
}
